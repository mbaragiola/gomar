package main

import (
	"encoding/json"
	"errors"
	"os"
	"reflect"
	"strings"
	"testing"
)

func TestOCRAnnotationPinned(t *testing.T) {
	path := os.Getenv("GOMAR_OCR_ANNOTATION_FIXTURE")
	if path == "" {
		t.Skip("paired fixture is generated by the pinned offline Foundation gate")
	}
	input, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var fixture struct {
		Entity    string
		Suppliers map[string]struct {
			ID         int64
			Name, CUIT string
			Active     bool
		}
		Cases []struct {
			Name                 string
			Annotation, Expected json.RawMessage
		}
	}
	if err := json.Unmarshal(input, &fixture); err != nil {
		t.Fatal(err)
	}
	if len(fixture.Cases) < 20 {
		t.Fatal("incomplete pinned annotation fixture")
	}
	lookup := func(cuit string) *ocrSupplier {
		s, ok := fixture.Suppliers[cuit]
		if !ok {
			return nil
		}
		return &ocrSupplier{ID: s.ID, Name: s.Name, CUIT: s.CUIT, Active: s.Active}
	}
	for _, sample := range fixture.Cases {
		t.Run(sample.Name, func(t *testing.T) {
			result, err := ocrSuggestions(sample.Annotation, fixture.Entity, lookup)
			if string(sample.Expected) == "null" {
				if !errors.Is(err, errOCRAnnotation) || result != nil {
					t.Fatalf("wanted invalid annotation, got %v (%v)", result, err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			actual, err := json.Marshal(result)
			if err != nil {
				t.Fatal(err)
			}
			var left, right any
			if json.Unmarshal(actual, &left) != nil || json.Unmarshal(sample.Expected, &right) != nil || !reflect.DeepEqual(left, right) {
				t.Fatalf("got %s, want %s", actual, sample.Expected)
			}
		})
	}
}

func TestOCRAnnotationRejectsIncompleteLocalJSON(t *testing.T) {
	for _, raw := range []string{"", "null", "{}", "{} {}", "\xff", strings.Repeat(" ", (1<<20)+1)} {
		result, err := ocrSuggestions([]byte(raw), "", func(string) *ocrSupplier { t.Fatal("lookup on invalid annotation"); return nil })
		if !errors.Is(err, errOCRAnnotation) || result != nil {
			t.Fatalf("wanted local JSON refusal, got %#v %v", result, err)
		}
	}
}
