CREATE TABLE mcp_stock_minimum_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL DEFAULT 'stock_minimum_change' CHECK(action='stock_minimum_change'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    minimum_digest BYTEA NOT NULL CHECK(octet_length(minimum_digest)=32),
    minimum_preview JSONB CHECK(jsonb_typeof(minimum_preview)='object' AND octet_length(minimum_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    product_id BIGINT,
    approved_minimum BIGINT,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    FOREIGN KEY(product_id,outlet_id) REFERENCES pos_products(id,outlet_id) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,action,request_id),
    CHECK((product_id IS NULL)=(approved_minimum IS NULL)),
    CHECK(approved_minimum BETWEEN 0 AND 1000000),
    CHECK((status='approved')=(product_id IS NOT NULL)),
    CHECK((status='pending' AND minimum_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND minimum_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_stock_minimum_proposal_actor_scope_recent ON mcp_stock_minimum_proposals(actor_id,entity_id,outlet_id,action,id DESC);
CREATE INDEX mcp_stock_minimum_proposal_expiry ON mcp_stock_minimum_proposals(expires_at,id);
CREATE INDEX mcp_stock_minimum_proposal_session ON mcp_stock_minimum_proposals(session_id);
