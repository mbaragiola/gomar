ALTER TABLE mcp_wiki_proposal_tokens ADD CONSTRAINT mcp_wiki_proposal_tokens_purpose_check
    CHECK(purpose IN ('wiki','document_draft','wiki_edit','stock_receipt'));

ALTER TABLE stock_movements ADD CONSTRAINT stock_movements_id_outlet_key UNIQUE(id,outlet_id);
CREATE TABLE mcp_stock_receipt_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    purpose TEXT NOT NULL DEFAULT 'stock_receipt' CHECK(purpose='stock_receipt'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    review_digest BYTEA NOT NULL CHECK(octet_length(review_digest)=32),
    receipt_preview JSONB CHECK(jsonb_typeof(receipt_preview)='object' AND octet_length(receipt_preview::text)<=2048),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    movement_id BIGINT,
    FOREIGN KEY(token_id,actor_id,entity_id,outlet_id,purpose)
        REFERENCES mcp_wiki_proposal_tokens(id,actor_id,entity_id,outlet_id,purpose) ON DELETE CASCADE,
    FOREIGN KEY(movement_id,outlet_id) REFERENCES stock_movements(id,outlet_id) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,request_id),
    CHECK((status='pending' AND receipt_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND receipt_preview IS NULL AND decided_at IS NOT NULL)),
    CHECK((status='approved')=(movement_id IS NOT NULL))
);
CREATE INDEX mcp_stock_receipt_proposal_actor_scope_recent ON mcp_stock_receipt_proposals(actor_id,entity_id,outlet_id,id DESC);
CREATE INDEX mcp_stock_receipt_proposal_expiry ON mcp_stock_receipt_proposals(expires_at,id);
CREATE INDEX mcp_stock_receipt_proposal_token ON mcp_stock_receipt_proposals(token_id);
