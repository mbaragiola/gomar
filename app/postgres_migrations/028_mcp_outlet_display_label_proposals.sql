CREATE TABLE mcp_outlet_display_label_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL DEFAULT 'outlet_display_label_change' CHECK(action='outlet_display_label_change'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    label_digest BYTEA NOT NULL CHECK(octet_length(label_digest)=32),
    label_preview JSONB CHECK(jsonb_typeof(label_preview)='object' AND octet_length(label_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    approved_name TEXT COLLATE "C",
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    UNIQUE(actor_id,entity_id,outlet_id,action,request_id),
    CHECK(char_length(approved_name) BETWEEN 1 AND 120),
    CHECK((status='approved')=(approved_name IS NOT NULL)),
    CHECK((status='pending' AND label_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND label_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_outlet_display_label_proposal_actor_scope_recent ON mcp_outlet_display_label_proposals(actor_id,entity_id,outlet_id,action,id DESC);
CREATE INDEX mcp_outlet_display_label_proposal_expiry ON mcp_outlet_display_label_proposals(expires_at,id);
CREATE INDEX mcp_outlet_display_label_proposal_session ON mcp_outlet_display_label_proposals(session_id);
