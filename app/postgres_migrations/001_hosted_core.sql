-- Shared accounts and tenant scope for the hosted vertical slice.
-- Legacy accounting, documents, media and reconciliation are not here.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT COLLATE "C" NOT NULL UNIQUE,
    password TEXT NOT NULL,
    active BOOLEAN NOT NULL,
    staff BOOLEAN NOT NULL,
    superuser BOOLEAN NOT NULL,
    last_login BIGINT
);

CREATE TABLE sessions (
    token_hash BYTEA PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    password_digest BYTEA NOT NULL,
    expires BIGINT NOT NULL
);
CREATE INDEX sessions_expires ON sessions(expires);

CREATE TABLE entities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    cuit TEXT COLLATE "C" NOT NULL UNIQUE,
    active BOOLEAN NOT NULL
);

CREATE TABLE outlets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    name TEXT COLLATE "C" NOT NULL,
    active BOOLEAN NOT NULL,
    UNIQUE(entity_id,name)
);

CREATE TABLE memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    role TEXT NOT NULL CHECK(role IN ('unassigned','administration','purchasing','accounting','read_only')),
    active BOOLEAN NOT NULL,
    UNIQUE(user_id,entity_id)
);
CREATE INDEX memberships_entity ON memberships(entity_id);

CREATE TABLE outlet_grants (
    membership_id BIGINT NOT NULL REFERENCES memberships(id) ON DELETE CASCADE,
    outlet_id BIGINT NOT NULL REFERENCES outlets(id),
    PRIMARY KEY(membership_id,outlet_id)
);

CREATE FUNCTION gomar.gomar_reject_history_mutation() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $history$
BEGIN
    RAISE EXCEPTION 'history is append-only' USING ERRCODE = '23514';
END;
$history$;

CREATE TABLE access_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    membership_id BIGINT NOT NULL REFERENCES memberships(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    action TEXT NOT NULL CHECK(action IN ('create_membership','update_membership')),
    before TEXT NOT NULL CHECK(before::json IS NOT NULL),
    after TEXT NOT NULL CHECK(after::json IS NOT NULL),
    occurred_at TEXT COLLATE "C" NOT NULL
);
CREATE TRIGGER access_events_immutable BEFORE UPDATE OR DELETE ON access_events
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_reject_history_mutation();

CREATE TABLE knowledge_articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id BIGINT NOT NULL REFERENCES outlets(id) ON DELETE RESTRICT,
    title TEXT NOT NULL CHECK(length(title) BETWEEN 1 AND 120),
    body TEXT NOT NULL CHECK(length(body) BETWEEN 1 AND 12000),
    search_text TEXT COLLATE "C" NOT NULL,
    version BIGINT NOT NULL CHECK(version >= 1),
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL
);
CREATE INDEX knowledge_articles_outlet_recent ON knowledge_articles(outlet_id,id DESC);

CREATE TABLE knowledge_article_versions (
    article_id BIGINT NOT NULL REFERENCES knowledge_articles(id) ON DELETE RESTRICT,
    version BIGINT NOT NULL CHECK(version >= 1),
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    recorded_at TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(article_id,version)
);
CREATE TRIGGER knowledge_article_versions_immutable BEFORE UPDATE OR DELETE ON knowledge_article_versions
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_reject_history_mutation();
