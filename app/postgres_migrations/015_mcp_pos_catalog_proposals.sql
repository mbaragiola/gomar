CREATE TABLE mcp_pos_catalog_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL CHECK(action IN ('pos_product_price_change','pos_product_availability_change')),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    change_digest BYTEA NOT NULL CHECK(octet_length(change_digest)=32),
    change_preview JSONB CHECK(jsonb_typeof(change_preview)='object' AND octet_length(change_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    product_id BIGINT,
    product_revision BIGINT,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    FOREIGN KEY(product_id,outlet_id,product_revision) REFERENCES pos_product_versions(product_id,outlet_id,revision) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,action,request_id),
    CHECK((product_id IS NULL)=(product_revision IS NULL)),
    CHECK((status='approved')=(product_id IS NOT NULL)),
    CHECK((status='pending' AND change_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND change_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_pos_catalog_proposal_actor_scope_recent ON mcp_pos_catalog_proposals(actor_id,entity_id,outlet_id,action,id DESC);
CREATE INDEX mcp_pos_catalog_proposal_expiry ON mcp_pos_catalog_proposals(expires_at,id);
CREATE INDEX mcp_pos_catalog_proposal_session ON mcp_pos_catalog_proposals(session_id);
