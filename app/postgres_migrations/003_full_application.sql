    actor_id BIGINT NOT NULL REFERENCES users(id),
    occurred_at TEXT COLLATE "C" NOT NULL,
    name_changed BOOLEAN NOT NULL,
    active_changed BOOLEAN NOT NULL
, action TEXT COLLATE "C" NOT NULL DEFAULT 'change'
    CHECK (action IN ('change','add')));

CREATE TABLE admin_supplier_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    occurred_at TEXT COLLATE "C" NOT NULL,
    name_changed BOOLEAN NOT NULL
, action TEXT COLLATE "C" NOT NULL DEFAULT 'change'
    CHECK (action IN ('change','add')), active_changed BOOLEAN NOT NULL DEFAULT false);

CREATE TABLE admin_legal_entity_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL UNIQUE REFERENCES entities(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    occurred_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE "intake_operations" (
    id TEXT COLLATE "C" PRIMARY KEY NOT NULL CHECK (id ~ '^[0-9a-f-]{36}$'),
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    outlet_id BIGINT NOT NULL REFERENCES outlets(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    status TEXT COLLATE "C" NOT NULL CHECK (status IN ('uploaded', 'processing', 'ready', 'failed', 'cancelled', 'expired', 'confirmed')),
    mime_type TEXT COLLATE "C" NOT NULL CHECK (mime_type IN ('image/png', 'image/jpeg')),
    size BIGINT NOT NULL CHECK (size BETWEEN 1 AND 10485760),
    digest TEXT COLLATE "C" NOT NULL CHECK (digest ~ '^[0-9a-f]{64}$'),
    storage_name TEXT COLLATE "C" UNIQUE CHECK (storage_name IS NULL OR storage_name='intake-' || id),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK (expires_at > created_at),
    CHECK (status IN ('cancelled', 'expired', 'confirmed') OR storage_name IS NOT NULL)
);

CREATE TABLE "ocr_consent_events" (
