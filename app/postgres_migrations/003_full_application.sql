-- PostgreSQL parity schema for ordinary supplier, document, AP and reconciliation data.
-- Preserve public date/clock and canonical JSON text exactly; nullable columns
-- retain their meaning. Scope IDs and minor units use 64-bit integers.
CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    name TEXT COLLATE "C" NOT NULL,
    cuit TEXT COLLATE "C" NOT NULL,
    active BOOLEAN NOT NULL, created_at TEXT COLLATE "C",
    CONSTRAINT suppliers_entity_cuit_unique UNIQUE (entity_id, cuit)
);

CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    outlet_id BIGINT NOT NULL REFERENCES outlets(id),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    issuer_cuit TEXT COLLATE "C" NOT NULL,
    document_type TEXT COLLATE "C" NOT NULL CHECK (document_type IN ('invoice', 'credit_note', 'debit_note')),
    letter TEXT COLLATE "C" NOT NULL,
    point_of_sale BIGINT NOT NULL CHECK (point_of_sale BETWEEN 0 AND 99999),
    number BIGINT NOT NULL CHECK (number BETWEEN 0 AND 99999999),
    issue_date TEXT COLLATE "C" NOT NULL,
    due_date TEXT COLLATE "C",
    currency TEXT COLLATE "C" NOT NULL CHECK (currency IN ('ARS', 'USD')),
    subtotal_minor BIGINT CHECK (subtotal_minor >= 0),
    tax_minor BIGINT CHECK (tax_minor >= 0),
    total_minor BIGINT NOT NULL CHECK (total_minor >= 0),
    description TEXT COLLATE "C" NOT NULL,
    status TEXT COLLATE "C" NOT NULL CHECK (status IN ('draft', 'reviewed')),
    revision BIGINT NOT NULL CHECK (revision >= 0),
    created_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL,
    deleted_at TEXT COLLATE "C", created_by_id BIGINT REFERENCES users(id), updated_by_id BIGINT REFERENCES users(id), deleted_by_id BIGINT REFERENCES users(id),
    CONSTRAINT documents_identity_unique UNIQUE(entity_id,issuer_cuit,document_type,letter,point_of_sale,number)
);

CREATE TABLE ap_payables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    outlet_id BIGINT NOT NULL REFERENCES outlets(id),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    source_document_id BIGINT NOT NULL UNIQUE REFERENCES documents(id),
    currency TEXT COLLATE "C" NOT NULL CHECK (currency IN ('ARS', 'USD')),
    original_minor BIGINT NOT NULL CHECK (original_minor BETWEEN 1 AND 99999999999999),
    balance_minor BIGINT NOT NULL CHECK (balance_minor BETWEEN 0 AND original_minor),
    state TEXT GENERATED ALWAYS AS (
        CASE WHEN balance_minor = 0 THEN 'settled'
             WHEN balance_minor = original_minor THEN 'open' ELSE 'partial' END
    ) STORED,
    supplier_name_snapshot TEXT COLLATE "C" NOT NULL,
    supplier_cuit_snapshot TEXT COLLATE "C" NOT NULL,
    document_reference_snapshot TEXT COLLATE "C" NOT NULL,
    issue_date_snapshot TEXT COLLATE "C" NOT NULL,
    due_date_snapshot TEXT COLLATE "C",
    posted_by_id BIGINT NOT NULL REFERENCES users(id),
    posted_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE document_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(id),
    storage_name TEXT COLLATE "C" NOT NULL UNIQUE CHECK (
        storage_name ~ '^document-[0-9a-f]{32}$'
    ),
    original_filename TEXT COLLATE "C" NOT NULL CHECK (length(original_filename) BETWEEN 1 AND 255),
    mime_type TEXT COLLATE "C" NOT NULL CHECK (mime_type IN ('image/png','image/jpeg')),
    size BIGINT NOT NULL CHECK (size BETWEEN 1 AND 10485760),
    created_by_id BIGINT NOT NULL REFERENCES users(id),
    created_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE document_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES documents(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    action TEXT COLLATE "C" NOT NULL CHECK (action IN ('create', 'update', 'delete', 'review', 'attach')),
    reason TEXT COLLATE "C" NOT NULL,
    occurred_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE reconciliation_read_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    state TEXT COLLATE "C" NOT NULL CHECK (state IN ('draft','review','closed','deleted')),
    revision BIGINT NOT NULL CHECK (revision>=1),
    rules_version BIGINT NOT NULL CHECK (rules_version>=1),
    match_reference BOOLEAN NOT NULL,
    created_at TEXT COLLATE "C" NOT NULL,
    closed_at TEXT COLLATE "C",
    deleted_at TEXT COLLATE "C",
    unresolved_count BIGINT CHECK (unresolved_count>=0),
    confirmed_count BIGINT NOT NULL DEFAULT 0 CHECK (confirmed_count>=0),
    rejected_count BIGINT NOT NULL DEFAULT 0 CHECK (rejected_count>=0)
    , created_by_id BIGINT REFERENCES users(id), updated_at TEXT COLLATE "C");

CREATE TABLE reconciliation_read_outlets (
    run_id BIGINT NOT NULL REFERENCES reconciliation_read_runs(id),
    outlet_id BIGINT NOT NULL REFERENCES outlets(id),
    PRIMARY KEY(run_id,outlet_id)
);

CREATE TABLE reconciliation_read_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES reconciliation_read_runs(id),
    side TEXT COLLATE "C" NOT NULL CHECK (side IN ('payments','cash_flow')),
    label TEXT COLLATE "C" NOT NULL,
    mapping TEXT COLLATE "C" NOT NULL CHECK (mapping::json IS NOT NULL),
    formats TEXT COLLATE "C" NOT NULL CHECK (formats::json IS NOT NULL),
    default_currency TEXT COLLATE "C",
    default_outlet_id BIGINT REFERENCES outlets(id),
    row_count BIGINT NOT NULL CHECK (row_count>=0), operation_key TEXT COLLATE "C", imported_by_id BIGINT REFERENCES users(id), imported_at TEXT COLLATE "C",
    UNIQUE(run_id,label)
);
CREATE UNIQUE INDEX reconciliation_source_run_identity ON reconciliation_read_sources(run_id,id);

CREATE TABLE reconciliation_detail_rows (
    run_id BIGINT NOT NULL,
    id BIGINT NOT NULL,
    source_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    record_number BIGINT NOT NULL CHECK(record_number>0),
    payload TEXT COLLATE "C" NOT NULL CHECK(json_typeof(payload::json)='object'),
    PRIMARY KEY(run_id,id),
    UNIQUE(run_id,source_id,record_number),
    CHECK((CASE WHEN json_typeof(payload::json->'id')='number'
                THEN (payload::json->>'id')::numeric=id END) IS TRUE
        AND (CASE WHEN json_typeof(payload::json->'outlet_id')='number'
                  THEN (payload::json->>'outlet_id')::numeric=outlet_id END) IS TRUE
        AND (CASE WHEN json_typeof(payload::json->'record_number')='number'
                  THEN (payload::json->>'record_number')::numeric=record_number END) IS TRUE),
    FOREIGN KEY(run_id,source_id) REFERENCES reconciliation_read_sources(run_id,id),
    FOREIGN KEY(run_id,outlet_id) REFERENCES reconciliation_read_outlets(run_id,outlet_id)
);

CREATE TABLE reconciliation_detail_events (
    run_id BIGINT NOT NULL REFERENCES reconciliation_read_runs(id),
    ordinal BIGINT NOT NULL CHECK(ordinal>0),
    payload TEXT COLLATE "C" NOT NULL CHECK(json_typeof(payload::json)='object'), actor_id BIGINT REFERENCES users(id), operation_key TEXT COLLATE "C",
    PRIMARY KEY(run_id,ordinal)
);

CREATE TABLE reconciliation_detail_groups (
    run_id BIGINT NOT NULL REFERENCES reconciliation_read_runs(id),
    ordinal BIGINT NOT NULL CHECK(ordinal>0),
    payload TEXT COLLATE "C" NOT NULL CHECK(json_typeof(payload::json)='object'),
    PRIMARY KEY(run_id,ordinal)
);

CREATE TABLE reconciliation_detail_members (
    run_id BIGINT NOT NULL,
    group_ordinal BIGINT NOT NULL,
    row_id BIGINT NOT NULL,
    ordinal BIGINT NOT NULL CHECK(ordinal>0),
    PRIMARY KEY(run_id,group_ordinal,row_id),
    UNIQUE(run_id,row_id),
    FOREIGN KEY(run_id,group_ordinal) REFERENCES reconciliation_detail_groups(run_id,ordinal),
    FOREIGN KEY(run_id,row_id) REFERENCES reconciliation_detail_rows(run_id,id)
);

CREATE TABLE reconciliation_source_highwater (
    singleton BIGINT PRIMARY KEY CHECK(singleton=1),
    source_id BIGINT NOT NULL CHECK(source_id>=0),
    row_id BIGINT NOT NULL CHECK(row_id>=0)
);

INSERT INTO reconciliation_source_highwater(singleton,source_id,row_id) VALUES(1,0,0);

CREATE TABLE "reconciliation_review_decisions" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES reconciliation_read_runs(id),
    group_ordinal BIGINT NOT NULL,
    payment_row_id BIGINT NOT NULL,
    cash_flow_row_id BIGINT NOT NULL,
    acknowledged BOOLEAN NOT NULL,
    operation_key TEXT COLLATE "C" NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES users(id), decision TEXT COLLATE "C" NOT NULL DEFAULT 'rejected'
    CHECK(decision IN ('rejected','confirmed')), decided_at TEXT COLLATE "C",
    UNIQUE(run_id,operation_key),
    UNIQUE(run_id,payment_row_id,cash_flow_row_id),
    FOREIGN KEY(run_id,group_ordinal,payment_row_id)
      REFERENCES reconciliation_detail_members(run_id,group_ordinal,row_id),
    FOREIGN KEY(run_id,group_ordinal,cash_flow_row_id)
      REFERENCES reconciliation_detail_members(run_id,group_ordinal,row_id)
);

CREATE TABLE admin_outlet_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
