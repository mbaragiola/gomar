    operation_id TEXT COLLATE "C" NOT NULL REFERENCES "intake_operations"(id),
    disclosure_version TEXT COLLATE "C" NOT NULL CHECK (length(disclosure_version) BETWEEN 1 AND 80),
    action TEXT COLLATE "C" NOT NULL CHECK (action = 'request_gemini_ocr'),
    occurred_at BIGINT NOT NULL
);

CREATE TABLE reconciliation_native_v1_runs (
    run_id BIGINT PRIMARY KEY REFERENCES reconciliation_read_runs(id)
);

CREATE TABLE ap_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    outlet_id BIGINT NOT NULL REFERENCES outlets(id),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    currency TEXT COLLATE "C" NOT NULL CHECK (currency IN ('ARS', 'USD')),
    total_minor BIGINT NOT NULL CHECK (total_minor BETWEEN 1 AND 99999999999999),
    method TEXT COLLATE "C" NOT NULL CHECK (method IN ('cash', 'bank_transfer')),
    reference TEXT COLLATE "C" NOT NULL CHECK (length(reference) <= 200),
    status TEXT COLLATE "C" NOT NULL CHECK (status IN ('draft', 'posted', 'reversed')),
    kind TEXT COLLATE "C" NOT NULL CHECK (kind IN ('payment', 'reversal')),
    reversal_of_id BIGINT UNIQUE REFERENCES ap_payments(id),
    reversal_reason TEXT COLLATE "C" NOT NULL,
    created_by_id BIGINT NOT NULL REFERENCES users(id),
    created_at TEXT COLLATE "C" NOT NULL,
    posted_by_id BIGINT REFERENCES users(id),
    posted_at TEXT COLLATE "C",
    post_key TEXT COLLATE "C" NOT NULL,
    CONSTRAINT ap_payments_post_key_unique UNIQUE (entity_id, created_by_id, post_key),
    CHECK (
        (status = 'draft' AND posted_by_id IS NULL AND posted_at IS NULL) OR
        (status <> 'draft' AND posted_by_id IS NOT NULL AND posted_at IS NOT NULL)
    ),
    CHECK (
        (kind = 'payment' AND reversal_of_id IS NULL AND reversal_reason = '') OR
        (kind = 'reversal' AND reversal_of_id <> id AND reversal_of_id IS NOT NULL
         AND status = 'posted' AND length(reversal_reason) BETWEEN 1 AND 500)
    )
);

CREATE TABLE ap_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES ap_payments(id),
    payable_id BIGINT NOT NULL REFERENCES ap_payables(id),
    amount_minor BIGINT NOT NULL CHECK (amount_minor BETWEEN 1 AND 99999999999999),
    reverses_id BIGINT UNIQUE REFERENCES ap_allocations(id),
    created_at TEXT COLLATE "C" NOT NULL,
    UNIQUE (payment_id, payable_id)
);

CREATE TABLE ap_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payable_id BIGINT NOT NULL REFERENCES ap_payables(id),
    payment_id BIGINT REFERENCES ap_payments(id),
    kind TEXT COLLATE "C" NOT NULL,
    delta_minor BIGINT NOT NULL,
    balance_minor BIGINT NOT NULL CHECK (balance_minor BETWEEN 0 AND 99999999999999),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    reason TEXT COLLATE "C" NOT NULL,
    occurred_at TEXT COLLATE "C" NOT NULL,
    CHECK (
        (kind = 'post' AND payment_id IS NULL AND delta_minor > 0) OR
        (kind = 'payment' AND payment_id IS NOT NULL AND delta_minor < 0) OR
        (kind = 'reversal' AND payment_id IS NOT NULL AND delta_minor > 0)
    )
);

CREATE TABLE ap_financial_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    payable_id BIGINT REFERENCES ap_payables(id),
    payment_id BIGINT REFERENCES ap_payments(id),
    action TEXT COLLATE "C" NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES users(id),
    reason TEXT COLLATE "C" NOT NULL,
    snapshot TEXT COLLATE "C" NOT NULL CHECK (snapshot::json IS NOT NULL),
    occurred_at TEXT COLLATE "C" NOT NULL,
    CHECK (
        (action = 'post_payable' AND payable_id IS NOT NULL AND payment_id IS NULL) OR
        (action IN ('create_draft', 'post_payment', 'reverse_payment', 'attach_receipt')
         AND payable_id IS NULL AND payment_id IS NOT NULL)
    )
);

CREATE TABLE ap_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL UNIQUE REFERENCES ap_payments(id),
    storage_name TEXT COLLATE "C" NOT NULL UNIQUE CHECK (storage_name ~ '^[0-9a-f]{32}$'),
    original_filename TEXT COLLATE "C" NOT NULL CHECK (length(original_filename) BETWEEN 1 AND 255),
    mime_type TEXT COLLATE "C" NOT NULL CHECK (mime_type IN ('image/png', 'image/jpeg')),
    size BIGINT NOT NULL CHECK (size BETWEEN 1 AND 10485760),
    uploaded_by_id BIGINT NOT NULL REFERENCES users(id),
    uploaded_at TEXT COLLATE "C" NOT NULL
);
