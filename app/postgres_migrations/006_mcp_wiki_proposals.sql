CREATE TABLE mcp_wiki_proposal_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    entity_id BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    outlet_id BIGINT NOT NULL REFERENCES outlets(id) ON DELETE CASCADE,
    token_hash BYTEA NOT NULL UNIQUE CHECK(octet_length(token_hash)=32),
    password_digest BYTEA NOT NULL CHECK(octet_length(password_digest)=32),
    issued_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at > issued_at AND expires_at <= issued_at+900),
    revoked_at BIGINT CHECK(revoked_at IS NULL OR revoked_at >= issued_at),
    UNIQUE(id,actor_id,entity_id,outlet_id)
);
CREATE INDEX mcp_wiki_proposal_tokens_actor_expiry ON mcp_wiki_proposal_tokens(actor_id,expires_at);
CREATE INDEX mcp_wiki_proposal_tokens_expiry ON mcp_wiki_proposal_tokens(expires_at,id);

CREATE TABLE mcp_wiki_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    request_id UUID NOT NULL,
    digest BYTEA NOT NULL CHECK(octet_length(digest)=32),
    title TEXT CHECK(length(title) BETWEEN 1 AND 120),
    body TEXT CHECK(length(body) BETWEEN 1 AND 12000 AND octet_length(body)<=49152),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at > created_at AND expires_at <= created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at >= created_at),
    article_id BIGINT REFERENCES knowledge_articles(id) ON DELETE RESTRICT,
    FOREIGN KEY(token_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_wiki_proposal_tokens(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    UNIQUE(actor_id,entity_id,outlet_id,request_id),
    CHECK(
        (status='pending' AND title IS NOT NULL AND body IS NOT NULL AND decided_at IS NULL) OR
        (status<>'pending' AND title IS NULL AND body IS NULL AND decided_at IS NOT NULL)
    ),
    CHECK((status='approved') = (article_id IS NOT NULL))
);
CREATE INDEX mcp_wiki_proposals_actor_scope_recent ON mcp_wiki_proposals(actor_id,entity_id,outlet_id,id DESC);
CREATE INDEX mcp_wiki_proposals_expiry ON mcp_wiki_proposals(expires_at,id);
CREATE INDEX mcp_wiki_proposals_token ON mcp_wiki_proposals(token_id);
