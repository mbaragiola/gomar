CREATE TABLE mcp_reservation_cancel_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL DEFAULT 'reservation_cancel' CHECK(action='reservation_cancel'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    cancellation_digest BYTEA NOT NULL CHECK(octet_length(cancellation_digest)=32),
    cancellation_preview JSONB CHECK(jsonb_typeof(cancellation_preview)='object' AND octet_length(cancellation_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    reservation_reference TEXT,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    FOREIGN KEY(reservation_reference) REFERENCES reservation_requests(id) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,action,request_id),
    CHECK((status='approved')=(reservation_reference IS NOT NULL)),
    CHECK((status='pending' AND cancellation_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND cancellation_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_reservation_cancel_proposal_actor_scope_recent ON mcp_reservation_cancel_proposals(actor_id,entity_id,outlet_id,action,id DESC);
CREATE INDEX mcp_reservation_cancel_proposal_expiry ON mcp_reservation_cancel_proposals(expires_at,id);
CREATE INDEX mcp_reservation_cancel_proposal_session ON mcp_reservation_cancel_proposals(session_id);
