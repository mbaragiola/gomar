ALTER TABLE mcp_proposal_session_actions DROP CONSTRAINT mcp_proposal_session_actions_action_check;
ALTER TABLE mcp_proposal_session_actions ADD CONSTRAINT mcp_proposal_session_actions_action_check
    CHECK(action IN ('pos_product_rename','document_draft_review','reconciliation_draft_create','document_draft_edit','stock_waste_record','stock_physical_count'));

CREATE TABLE mcp_stock_adjustment_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL CHECK(action IN ('stock_waste_record','stock_physical_count')),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    adjustment_digest BYTEA NOT NULL CHECK(octet_length(adjustment_digest)=32),
    adjustment_preview JSONB CHECK(jsonb_typeof(adjustment_preview)='object' AND octet_length(adjustment_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    movement_id BIGINT,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    FOREIGN KEY(movement_id) REFERENCES stock_movements(id) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,action,request_id),
    CHECK((status='approved')=(movement_id IS NOT NULL)),
    CHECK((status='pending' AND adjustment_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND adjustment_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_stock_adjustment_proposal_actor_scope_recent ON mcp_stock_adjustment_proposals(actor_id,entity_id,outlet_id,action,id DESC);
CREATE INDEX mcp_stock_adjustment_proposal_expiry ON mcp_stock_adjustment_proposals(expires_at,id);
CREATE INDEX mcp_stock_adjustment_proposal_session ON mcp_stock_adjustment_proposals(session_id);
