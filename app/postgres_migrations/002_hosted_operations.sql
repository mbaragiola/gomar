-- Reservations and menus, including historical cancellation policy wording.
CREATE TABLE reservation_venues (
    outlet_id BIGINT PRIMARY KEY REFERENCES outlets(id),
    slug TEXT COLLATE "C" NOT NULL UNIQUE CHECK(length(slug) BETWEEN 1 AND 48),
    display_name TEXT NOT NULL CHECK(length(display_name) BETWEEN 1 AND 80),
    cancellation_policy TEXT NOT NULL CHECK(length(cancellation_policy) <= 500),
    enabled BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE reservation_tables (
    outlet_id BIGINT NOT NULL REFERENCES reservation_venues(outlet_id),
    label TEXT COLLATE "C" NOT NULL CHECK(length(label) BETWEEN 1 AND 32),
    capacity INTEGER NOT NULL CHECK(capacity BETWEEN 1 AND 12),
    PRIMARY KEY(outlet_id,label)
);

CREATE TABLE reservation_slots (
    outlet_id BIGINT NOT NULL REFERENCES reservation_venues(outlet_id),
    start_at TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(outlet_id,start_at)
);

CREATE TABLE reservation_requests (
    id TEXT COLLATE "C" PRIMARY KEY CHECK(length(id)=32),
    outlet_id BIGINT NOT NULL,
    start_at TEXT COLLATE "C" NOT NULL,
    guest_name TEXT NOT NULL CHECK(length(guest_name) BETWEEN 1 AND 80),
    party_size INTEGER NOT NULL CHECK(party_size BETWEEN 1 AND 12),
    status TEXT NOT NULL CHECK(status IN ('pending','confirmed','cancelled')),
    table_label TEXT COLLATE "C",
    created_at TEXT COLLATE "C" NOT NULL,
    FOREIGN KEY(outlet_id,start_at) REFERENCES reservation_slots(outlet_id,start_at),
    FOREIGN KEY(outlet_id,table_label) REFERENCES reservation_tables(outlet_id,label),
    CHECK((status='confirmed')=(table_label IS NOT NULL))
);
CREATE INDEX reservation_requests_slot ON reservation_requests(outlet_id,start_at,id);
CREATE UNIQUE INDEX reservation_confirmed_table ON reservation_requests(outlet_id,start_at,table_label)
    WHERE status='confirmed';

CREATE TABLE reservation_request_policies (
    request_id TEXT COLLATE "C" PRIMARY KEY REFERENCES reservation_requests(id) ON DELETE CASCADE,
    policy TEXT NOT NULL CHECK(length(policy) <= 500)
);

CREATE FUNCTION gomar.gomar_capture_reservation_policy() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $policy$
BEGIN
    INSERT INTO gomar.reservation_request_policies(request_id,policy)
    SELECT NEW.id, cancellation_policy FROM gomar.reservation_venues WHERE outlet_id=NEW.outlet_id;
    RETURN NEW;
END;
$policy$;
CREATE TRIGGER reservation_capture_policy AFTER INSERT ON reservation_requests
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_capture_reservation_policy();

CREATE TABLE reservation_menus (
    outlet_id BIGINT PRIMARY KEY REFERENCES reservation_venues(outlet_id) ON DELETE CASCADE,
    body BYTEA NOT NULL CHECK(octet_length(body) BETWEEN 16 AND 4194304),
    updated_at TEXT COLLATE "C" NOT NULL,
    updated_by BIGINT NOT NULL REFERENCES users(id)
);

CREATE TABLE reservation_concierge_events (
    outlet_id BIGINT NOT NULL REFERENCES reservation_venues(outlet_id),
    fingerprint BYTEA NOT NULL CHECK(octet_length(fingerprint)=32),
    reservation_id TEXT COLLATE "C" NOT NULL UNIQUE REFERENCES reservation_requests(id) ON DELETE CASCADE,
    PRIMARY KEY(outlet_id,fingerprint)
);

-- POS uses integer minor units and immutable historical catalog versions.
CREATE TABLE pos_products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id BIGINT NOT NULL REFERENCES outlets(id) ON DELETE RESTRICT,
    current_revision BIGINT NOT NULL CHECK(current_revision >= 1),
    UNIQUE(id,outlet_id)
);
CREATE INDEX pos_products_outlet ON pos_products(outlet_id,id);

CREATE TABLE pos_product_versions (
    product_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    revision BIGINT NOT NULL CHECK(revision >= 1),
    name TEXT NOT NULL CHECK(length(name) BETWEEN 1 AND 120),
    price_minor BIGINT NOT NULL CHECK(price_minor BETWEEN 1 AND 100000000),
    active BOOLEAN NOT NULL,
    PRIMARY KEY(product_id,outlet_id,revision),
    FOREIGN KEY(product_id,outlet_id) REFERENCES pos_products(id,outlet_id) ON DELETE RESTRICT
);
ALTER TABLE pos_products ADD CONSTRAINT pos_products_current_version
    FOREIGN KEY(id,outlet_id,current_revision)
    REFERENCES pos_product_versions(product_id,outlet_id,revision) DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE pos_sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id TEXT COLLATE "C" NOT NULL UNIQUE CHECK(length(request_id)=36),
    outlet_id BIGINT NOT NULL REFERENCES outlets(id) ON DELETE RESTRICT,
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    total_minor BIGINT NOT NULL CHECK(total_minor BETWEEN 1 AND 10000000000),
    recorded_at TEXT COLLATE "C" NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'efectivo'
        CHECK(payment_method IN ('debito','credito','qr_modo','qr_mercado_pago','transferencia','efectivo')),
    UNIQUE(id,outlet_id)
);

CREATE TABLE pos_sale_items (
    sale_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    revision BIGINT NOT NULL,
    quantity BIGINT NOT NULL CHECK(quantity BETWEEN 1 AND 999),
    PRIMARY KEY(sale_id,product_id),
    FOREIGN KEY(sale_id,outlet_id) REFERENCES pos_sales(id,outlet_id) ON DELETE RESTRICT,
    FOREIGN KEY(product_id,outlet_id,revision)
        REFERENCES pos_product_versions(product_id,outlet_id,revision) ON DELETE RESTRICT
);
CREATE TRIGGER pos_product_versions_immutable BEFORE UPDATE OR DELETE ON pos_product_versions
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_reject_history_mutation();
CREATE TRIGGER pos_sales_immutable BEFORE UPDATE OR DELETE ON pos_sales
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_reject_history_mutation();
CREATE TRIGGER pos_sale_items_immutable BEFORE UPDATE OR DELETE ON pos_sale_items
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_reject_history_mutation();

-- Stock is an append-only estimate ledger. Negative balances remain valid.
CREATE TABLE stock_outlets (
    outlet_id BIGINT PRIMARY KEY REFERENCES outlets(id) ON DELETE RESTRICT,
    enabled BOOLEAN NOT NULL
);

CREATE TABLE stock_products (
    outlet_id BIGINT NOT NULL REFERENCES stock_outlets(outlet_id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL,
    enabled BOOLEAN NOT NULL,
    minimum BIGINT NOT NULL CHECK(minimum BETWEEN 0 AND 1000000),
    PRIMARY KEY(outlet_id,product_id),
    FOREIGN KEY(product_id,outlet_id) REFERENCES pos_products(id,outlet_id) ON DELETE RESTRICT
);

CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    outlet_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    kind TEXT NOT NULL CHECK(kind IN ('recepcion','merma','conteo','venta')),
    quantity BIGINT NOT NULL CHECK(quantity BETWEEN 0 AND 1000000),
    delta BIGINT NOT NULL,
    recorded_at TEXT COLLATE "C" NOT NULL,
    request_id TEXT COLLATE "C",
    sale_id BIGINT,
    FOREIGN KEY(outlet_id,product_id) REFERENCES stock_products(outlet_id,product_id) ON DELETE RESTRICT,
    FOREIGN KEY(sale_id,outlet_id) REFERENCES pos_sales(id,outlet_id) ON DELETE RESTRICT,
    FOREIGN KEY(sale_id,product_id) REFERENCES pos_sale_items(sale_id,product_id) ON DELETE RESTRICT,
    UNIQUE(outlet_id,request_id),
    UNIQUE(sale_id,product_id),
    CHECK((kind='venta' AND request_id IS NULL AND sale_id IS NOT NULL AND quantity BETWEEN 1 AND 999 AND delta=-quantity)
       OR (kind!='venta' AND request_id IS NOT NULL AND length(request_id)=36 AND sale_id IS NULL
            AND ((kind='recepcion' AND quantity>0 AND delta=quantity)
              OR (kind='merma' AND quantity>0 AND delta=-quantity) OR kind='conteo')))
);
CREATE INDEX stock_movements_product ON stock_movements(outlet_id,product_id,id);
CREATE TRIGGER stock_movements_immutable BEFORE UPDATE OR DELETE ON stock_movements
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_reject_history_mutation();

-- Preserve exact JSON text for delivery replay equality. This schema alone
-- does not expose provider ingress or sign up a live provider.
CREATE TABLE delivery_sources (
    provider TEXT COLLATE "C" NOT NULL,
    external_store_id TEXT COLLATE "C" NOT NULL,
    outlet_id BIGINT NOT NULL REFERENCES outlets(id) ON DELETE RESTRICT,
    PRIMARY KEY(provider,external_store_id),
    UNIQUE(provider,external_store_id,outlet_id)
);

CREATE TABLE delivery_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT COLLATE "C" NOT NULL,
    external_store_id TEXT COLLATE "C" NOT NULL,
    external_order_id TEXT COLLATE "C" NOT NULL,
    outlet_id BIGINT NOT NULL,
    accepted_items TEXT,
    cancelled BOOLEAN NOT NULL,
    received_at TEXT COLLATE "C" NOT NULL,
    updated_at TEXT COLLATE "C" NOT NULL,
    CHECK(cancelled OR accepted_items IS NOT NULL),
    UNIQUE(provider,external_store_id,external_order_id),
    UNIQUE(id,provider,external_store_id),
    FOREIGN KEY(provider,external_store_id,outlet_id)
        REFERENCES delivery_sources(provider,external_store_id,outlet_id) ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX delivery_orders_inbox ON delivery_orders(outlet_id,updated_at DESC,id DESC);

CREATE TABLE delivery_order_events (
    provider TEXT COLLATE "C" NOT NULL,
    external_store_id TEXT COLLATE "C" NOT NULL,
    external_event_id TEXT COLLATE "C" NOT NULL,
    order_id BIGINT NOT NULL,
    event_kind TEXT NOT NULL CHECK(event_kind IN ('accepted','received','cancelled')),
    digest TEXT NOT NULL CHECK(length(digest)=64),
    recorded_at TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY(provider,external_store_id,external_event_id),
    FOREIGN KEY(order_id,provider,external_store_id)
        REFERENCES delivery_orders(id,provider,external_store_id) ON DELETE RESTRICT
);
