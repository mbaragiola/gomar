ALTER TABLE mcp_wiki_proposal_tokens DROP CONSTRAINT mcp_wiki_proposal_tokens_purpose_check;
ALTER TABLE mcp_wiki_proposal_tokens ADD CONSTRAINT mcp_wiki_proposal_tokens_purpose_check
    CHECK(purpose IN ('wiki','document_draft','wiki_edit'));

CREATE TABLE mcp_wiki_edit_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    purpose TEXT NOT NULL DEFAULT 'wiki_edit' CHECK(purpose='wiki_edit'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    review_digest BYTEA NOT NULL CHECK(octet_length(review_digest)=32),
    -- Store only the bounded, typed preview generated by the Go adapter.
    edit_preview JSONB CHECK(jsonb_typeof(edit_preview)='object' AND octet_length(edit_preview::text)<=153600),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    article_id BIGINT,
    article_version BIGINT,
    FOREIGN KEY(token_id,actor_id,entity_id,outlet_id,purpose)
        REFERENCES mcp_wiki_proposal_tokens(id,actor_id,entity_id,outlet_id,purpose) ON DELETE CASCADE,
    FOREIGN KEY(article_id,article_version) REFERENCES knowledge_article_versions(article_id,version)
        MATCH FULL ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,request_id),
    CHECK((status='pending' AND edit_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND edit_preview IS NULL AND decided_at IS NOT NULL)),
    CHECK((status='approved')=(article_id IS NOT NULL AND article_version IS NOT NULL))
);
CREATE INDEX mcp_wiki_edit_proposal_actor_scope_recent ON mcp_wiki_edit_proposals(actor_id,entity_id,outlet_id,id DESC);
CREATE INDEX mcp_wiki_edit_proposal_expiry ON mcp_wiki_edit_proposals(expires_at,id);
CREATE INDEX mcp_wiki_edit_proposal_token ON mcp_wiki_edit_proposals(token_id);
