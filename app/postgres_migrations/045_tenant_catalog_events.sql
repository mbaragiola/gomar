CREATE TABLE tenant_catalog_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    outlet_id BIGINT,
    actor_id BIGINT NOT NULL REFERENCES users(id),
    action TEXT NOT NULL,
    before JSONB NOT NULL CHECK(jsonb_typeof(before) = 'object'),
    after JSONB NOT NULL CHECK(jsonb_typeof(after) = 'object'),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    FOREIGN KEY(outlet_id,entity_id) REFERENCES outlets(id,entity_id),
    CHECK ((action = 'update_entity' AND outlet_id IS NULL) OR
           (action IN ('create_outlet','update_outlet') AND outlet_id IS NOT NULL))
);
CREATE TRIGGER tenant_catalog_events_immutable
    BEFORE UPDATE OR DELETE ON tenant_catalog_events
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_reject_history_mutation();
