ALTER TABLE mcp_proposal_session_actions DROP CONSTRAINT mcp_proposal_session_actions_action_check;
ALTER TABLE mcp_proposal_session_actions ADD CONSTRAINT mcp_proposal_session_actions_action_check
    CHECK(action IN ('pos_product_rename','document_draft_review','reconciliation_draft_create'));

CREATE TABLE mcp_reconciliation_draft_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL DEFAULT 'reconciliation_draft_create' CHECK(action='reconciliation_draft_create'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    draft_digest BYTEA NOT NULL CHECK(octet_length(draft_digest)=32),
    draft_preview JSONB CHECK(jsonb_typeof(draft_preview)='object' AND octet_length(draft_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    run_id BIGINT,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    FOREIGN KEY(run_id) REFERENCES reconciliation_read_runs(id) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,request_id),
    CHECK((status='approved')=(run_id IS NOT NULL)),
    CHECK((status='pending' AND draft_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND draft_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_reconciliation_draft_proposal_actor_scope_recent ON mcp_reconciliation_draft_proposals(actor_id,entity_id,outlet_id,id DESC);
CREATE INDEX mcp_reconciliation_draft_proposal_expiry ON mcp_reconciliation_draft_proposals(expires_at,id);
CREATE INDEX mcp_reconciliation_draft_proposal_session ON mcp_reconciliation_draft_proposals(session_id);
