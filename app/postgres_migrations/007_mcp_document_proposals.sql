-- Keep the original wiki migration immutable. Purpose is chosen by the
-- dedicated credential route, not by a caller, and enforced by both FKs.
ALTER TABLE mcp_wiki_proposal_tokens ADD COLUMN purpose TEXT NOT NULL DEFAULT 'wiki'
    CHECK(purpose IN ('wiki','document_draft'));
ALTER TABLE mcp_wiki_proposal_tokens ADD CONSTRAINT mcp_proposal_token_scope_purpose_key
    UNIQUE(id,actor_id,entity_id,outlet_id,purpose);
ALTER TABLE mcp_wiki_proposals ADD COLUMN purpose TEXT NOT NULL DEFAULT 'wiki' CHECK(purpose='wiki');
ALTER TABLE mcp_wiki_proposals ADD FOREIGN KEY(token_id,actor_id,entity_id,outlet_id,purpose)
    REFERENCES mcp_wiki_proposal_tokens(id,actor_id,entity_id,outlet_id,purpose) ON DELETE CASCADE;

CREATE TABLE mcp_document_draft_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    purpose TEXT NOT NULL DEFAULT 'document_draft' CHECK(purpose='document_draft'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    review_digest BYTEA NOT NULL CHECK(octet_length(review_digest)=32),
    supplier_fingerprint BYTEA CHECK(octet_length(supplier_fingerprint)=32),
    -- A versioned, bounded snapshot encoded from the Go document preview
    -- type, never accepted directly from an HTTP request.
    draft_preview JSONB CHECK(jsonb_typeof(draft_preview)='object' AND octet_length(draft_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    document_id BIGINT REFERENCES documents(id) ON DELETE RESTRICT,
    FOREIGN KEY(token_id,actor_id,entity_id,outlet_id,purpose)
        REFERENCES mcp_wiki_proposal_tokens(id,actor_id,entity_id,outlet_id,purpose) ON DELETE CASCADE,
    UNIQUE(actor_id,entity_id,outlet_id,request_id),
    CHECK((status='pending' AND supplier_fingerprint IS NOT NULL AND draft_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND supplier_fingerprint IS NULL AND draft_preview IS NULL AND decided_at IS NOT NULL)),
    CHECK((status='approved')=(document_id IS NOT NULL))
);
CREATE INDEX mcp_document_proposal_actor_scope_recent ON mcp_document_draft_proposals(actor_id,entity_id,outlet_id,id DESC);
CREATE INDEX mcp_document_proposal_expiry ON mcp_document_draft_proposals(expires_at,id);
CREATE INDEX mcp_document_proposal_token ON mcp_document_draft_proposals(token_id);
