CREATE TABLE mcp_read_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    entity_id BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    outlet_id BIGINT REFERENCES outlets(id) ON DELETE CASCADE,
    token_hash BYTEA NOT NULL UNIQUE CHECK(octet_length(token_hash)=32),
    password_digest BYTEA NOT NULL CHECK(octet_length(password_digest)=32),
    issued_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at > issued_at AND expires_at <= issued_at + 900)
);
CREATE INDEX mcp_read_tokens_user_expiry ON mcp_read_tokens(user_id,expires_at);
CREATE INDEX pos_sales_outlet_recorded ON pos_sales(outlet_id,recorded_at);
