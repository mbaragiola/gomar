-- Add a deliberately separate credential. Legacy token scope and purposes do
-- not change. Deleting a login must not cascade through approval receipts.
CREATE TABLE mcp_proposal_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    entity_id BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    outlet_id BIGINT NOT NULL REFERENCES outlets(id) ON DELETE CASCADE,
    login_hash BYTEA NOT NULL CHECK(octet_length(login_hash)=32),
    bearer_hash BYTEA NOT NULL UNIQUE CHECK(octet_length(bearer_hash)=32),
    password_digest BYTEA NOT NULL CHECK(octet_length(password_digest)=32),
    issued_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>issued_at AND expires_at<=issued_at+900),
    revoked_at BIGINT CHECK(revoked_at IS NULL OR revoked_at>=issued_at),
    UNIQUE(id,actor_id,entity_id,outlet_id)
);
CREATE INDEX mcp_proposal_sessions_actor_expiry ON mcp_proposal_sessions(actor_id,expires_at);
CREATE INDEX mcp_proposal_sessions_expiry ON mcp_proposal_sessions(expires_at,id);

CREATE TABLE mcp_proposal_session_actions (
    session_id BIGINT NOT NULL REFERENCES mcp_proposal_sessions(id) ON DELETE CASCADE,
    action TEXT NOT NULL CHECK(action='pos_product_rename'),
    PRIMARY KEY(session_id,action)
);
CREATE TRIGGER mcp_proposal_session_action_no_update BEFORE UPDATE ON mcp_proposal_session_actions
    FOR EACH ROW EXECUTE FUNCTION gomar.gomar_reject_history_mutation();

CREATE TABLE mcp_pos_rename_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL DEFAULT 'pos_product_rename' CHECK(action='pos_product_rename'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    review_digest BYTEA NOT NULL CHECK(octet_length(review_digest)=32),
    rename_preview JSONB CHECK(jsonb_typeof(rename_preview)='object' AND octet_length(rename_preview::text)<=2048),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    product_id BIGINT,
    product_revision BIGINT,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    FOREIGN KEY(product_id,outlet_id,product_revision)
        REFERENCES pos_product_versions(product_id,outlet_id,revision) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,request_id),
    CHECK((product_id IS NULL)=(product_revision IS NULL)),
    CHECK((status='approved')=(product_id IS NOT NULL)),
    CHECK((status='pending' AND rename_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND rename_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_pos_rename_proposal_actor_scope_recent ON mcp_pos_rename_proposals(actor_id,entity_id,outlet_id,id DESC);
CREATE INDEX mcp_pos_rename_proposal_expiry ON mcp_pos_rename_proposals(expires_at,id);
CREATE INDEX mcp_pos_rename_proposal_session ON mcp_pos_rename_proposals(session_id);
