ALTER TABLE mcp_proposal_session_actions DROP CONSTRAINT mcp_proposal_session_actions_action_check;
ALTER TABLE mcp_proposal_session_actions ADD CONSTRAINT mcp_proposal_session_actions_action_check
    CHECK(action IN ('pos_product_rename','document_draft_review'));

CREATE TABLE mcp_document_review_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL DEFAULT 'document_draft_review' CHECK(action='document_draft_review'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    review_digest BYTEA NOT NULL CHECK(octet_length(review_digest)=32),
    review_preview JSONB CHECK(jsonb_typeof(review_preview)='object' AND octet_length(review_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    document_id BIGINT,
    document_revision BIGINT,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    FOREIGN KEY(document_id) REFERENCES documents(id) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,request_id),
    CHECK((document_id IS NULL)=(document_revision IS NULL)),
    CHECK((status='approved')=(document_id IS NOT NULL)),
    CHECK((status='pending' AND review_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND review_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_document_review_proposal_actor_scope_recent ON mcp_document_review_proposals(actor_id,entity_id,outlet_id,id DESC);
CREATE INDEX mcp_document_review_proposal_expiry ON mcp_document_review_proposals(expires_at,id);
CREATE INDEX mcp_document_review_proposal_session ON mcp_document_review_proposals(session_id);
