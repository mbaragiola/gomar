CREATE TABLE mcp_reservation_table_add_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL DEFAULT 'reservation_table_add' CHECK(action='reservation_table_add'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    table_digest BYTEA NOT NULL CHECK(octet_length(table_digest)=32),
    table_preview JSONB CHECK(jsonb_typeof(table_preview)='object' AND octet_length(table_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    table_label TEXT COLLATE "C",
    approved_capacity INTEGER,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    UNIQUE(actor_id,entity_id,outlet_id,action,request_id),
    CHECK((table_label IS NULL)=(approved_capacity IS NULL)),
    CHECK(approved_capacity BETWEEN 1 AND 12),
    CHECK(table_label ~ '^Mesa [1-9][0-9]{0,3}$'),
    CHECK((status='approved')=(table_label IS NOT NULL)),
    CHECK((status='pending' AND table_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND table_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_reservation_table_add_proposal_actor_scope_recent ON mcp_reservation_table_add_proposals(actor_id,entity_id,outlet_id,action,id DESC);
CREATE INDEX mcp_reservation_table_add_proposal_expiry ON mcp_reservation_table_add_proposals(expires_at,id);
CREATE INDEX mcp_reservation_table_add_proposal_session ON mcp_reservation_table_add_proposals(session_id);
