CREATE TABLE mcp_supplier_legal_name_proposals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL,
    entity_id BIGINT NOT NULL,
    outlet_id BIGINT NOT NULL,
    action TEXT NOT NULL DEFAULT 'supplier_legal_name_change' CHECK(action='supplier_legal_name_change'),
    request_id UUID NOT NULL,
    input_digest BYTEA NOT NULL CHECK(octet_length(input_digest)=32),
    supplier_digest BYTEA NOT NULL CHECK(octet_length(supplier_digest)=32),
    supplier_preview JSONB CHECK(jsonb_typeof(supplier_preview)='object' AND octet_length(supplier_preview::text)<=4096),
    status TEXT NOT NULL CHECK(status IN ('pending','approved','rejected','expired','revoked')),
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL CHECK(expires_at>created_at AND expires_at<=created_at+900),
    decided_at BIGINT CHECK(decided_at IS NULL OR decided_at>=created_at),
    supplier_id BIGINT,
    supplier_revision BIGINT,
    FOREIGN KEY(session_id,actor_id,entity_id,outlet_id)
        REFERENCES mcp_proposal_sessions(id,actor_id,entity_id,outlet_id) ON DELETE CASCADE,
    FOREIGN KEY(session_id,action) REFERENCES mcp_proposal_session_actions(session_id,action) ON DELETE CASCADE,
    FOREIGN KEY(supplier_id) REFERENCES suppliers(id) ON DELETE RESTRICT,
    UNIQUE(actor_id,entity_id,outlet_id,action,request_id),
    CHECK((supplier_id IS NULL)=(supplier_revision IS NULL)),
    CHECK(supplier_revision >= 2),
    CHECK((status='approved')=(supplier_id IS NOT NULL)),
    CHECK((status='pending' AND supplier_preview IS NOT NULL AND decided_at IS NULL)
       OR (status<>'pending' AND supplier_preview IS NULL AND decided_at IS NOT NULL))
);
CREATE INDEX mcp_supplier_legal_name_proposal_actor_scope_recent ON mcp_supplier_legal_name_proposals(actor_id,entity_id,outlet_id,action,id DESC);
CREATE INDEX mcp_supplier_legal_name_proposal_expiry ON mcp_supplier_legal_name_proposals(expires_at,id);
CREATE INDEX mcp_supplier_legal_name_proposal_session ON mcp_supplier_legal_name_proposals(session_id);

-- Proposal receipts expire. Keep a separate minimal record of applied changes.
CREATE TABLE mcp_supplier_legal_name_audit (
    actor_id BIGINT NOT NULL REFERENCES users(id),
    entity_id BIGINT NOT NULL REFERENCES entities(id),
    authorization_outlet_id BIGINT NOT NULL REFERENCES outlets(id),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
    supplier_revision BIGINT NOT NULL CHECK(supplier_revision >= 2),
    approved_at BIGINT NOT NULL,
    PRIMARY KEY(supplier_id,supplier_revision)
);
