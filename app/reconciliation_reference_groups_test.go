func TestReconciliationGroupsPinnedOracle(t *testing.T) {
	file := os.Getenv("GOMAR_REFERENCE_GROUPS_FIXTURE")
	if file == "" {
		t.Skip("pinned oracle fixture is generated by the foundation gate")
	}
	data, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	var cases []struct {
		Mode     string                         `json:"mode"`
		Name     string                         `json:"name"`
		Rows     []reconciliationReferenceRow   `json:"rows"`
		Expected []reconciliationReferenceGroup `json:"expected"`
	}
	if err := json.Unmarshal(data, &cases); err != nil {
		t.Fatal(err)
	}
	counts := map[string]int{}
	for _, tc := range cases {
		counts[tc.Mode]++
		t.Run(tc.Mode+"/"+tc.Name, func(t *testing.T) {
			var group func([]reconciliationReferenceRow) ([]reconciliationReferenceGroup, error)
			switch tc.Mode {
			case "exact-reference":
				group = buildExactReferenceGroups
			case "non-reference":
				group = buildNonReferenceGroups
			default:
				t.Fatalf("invalid oracle mode %q", tc.Mode)
			}
			got, err := group(tc.Rows)
			if err != nil || !reflect.DeepEqual(got, tc.Expected) {
				t.Fatalf("groups = %#v, error = %v; want %#v", got, err, tc.Expected)
			}
		})
	}
	if counts["exact-reference"] < 10 || counts["non-reference"] < 10 || counts["exact-reference"] != counts["non-reference"] {
		t.Fatalf("each oracle fixture must run in both modes: %v", counts)
	}
}

func TestExactReferenceGroupsBoundsAndUnsupported(t *testing.T) {
	base := reconciliationReferenceRow{ID: 1, Side: "payments", Outlet: 1, Date: "2026-11-01", Amount: 0, Currency: "ARS", Reference: "demo"}
	for _, alter := range []func(*reconciliationReferenceRow){
		func(r *reconciliationReferenceRow) { r.ID = 0 },
		func(r *reconciliationReferenceRow) { r.Side = "unspecified" },
		func(r *reconciliationReferenceRow) { r.Outlet = 0 },
		func(r *reconciliationReferenceRow) { r.Date = "2026-02-30" },
		func(r *reconciliationReferenceRow) { r.Currency = "EUR" },
		func(r *reconciliationReferenceRow) { r.Amount = 100000000000000 },
	} {
		bad := base
		alter(&bad)
		if out, err := buildExactReferenceGroups([]reconciliationReferenceRow{bad}); err == nil || out != nil {
			t.Fatalf("unsupported normalized row returned groups %#v: %v", out, err)
		}
	}
	if out, err := buildExactReferenceGroups([]reconciliationReferenceRow{base, base}); err == nil || out != nil {
		t.Fatal("duplicate ID accepted")
	}
	if out, err := buildExactReferenceGroups(make([]reconciliationReferenceRow, 20001)); err == nil || out != nil {
		t.Fatal("oversize fixture accepted")
	}
	check := base
	check.ID = 2
	check.Side = "cash_flow"
	check.Reference = ""
	result, err := buildExactReferenceGroups([]reconciliationReferenceRow{base, check})
	if err != nil || len(result) != 2 || result[0].Kind != "unmatched" || result[1].Kind != "unmatched" {
		t.Fatalf("blank reference matched: %#v %v", result, err)
	}
}

func TestNonReferenceGroupsIgnoresReferencesWithoutChangingSigns(t *testing.T) {
	payment := reconciliationReferenceRow{ID: 1, Side: "payments", Outlet: 1, Date: "2026-11-01", Amount: -250, Currency: "USD", Reference: ""}
	cash := payment
	cash.ID, cash.Side, cash.Reference = 2, "cash_flow", "Diferente"
	opposite := cash
	opposite.ID, opposite.Amount = 3, 250
	got, err := buildNonReferenceGroups([]reconciliationReferenceRow{payment, cash, opposite})
	if err != nil || len(got) != 2 || got[0].Kind != "candidate" || got[1].Kind != "unmatched" ||
		!reflect.DeepEqual(got[0].Payments, []int64{1}) || !reflect.DeepEqual(got[0].CashFlow, []int64{2}) {
		t.Fatalf("non-reference results = %#v, %v", got, err)
	}
	invalid := cash
	invalid.Side = "other"
	if out, err := buildNonReferenceGroups([]reconciliationReferenceRow{payment, invalid}); err == nil || out != nil {
		t.Fatalf("unsupported normalized data should not yield a partial group result: %#v, %v", out, err)
	}
}
